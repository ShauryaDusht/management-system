def seed_varieties(apps, schema_editor):
    PlantVariety = apps.get_model('geo_tracker', 'PlantVariety')
    for plant_type, varieties in (('tree', TREE_VARIETIES), ('plant', PLANT_VARIETIES)):
        for name, scientific_name in varieties:
            PlantVariety.objects.update_or_create(
                name=name,
                plant_type=plant_type,
                defaults={'scientific_name': scientific_name},
            )


def remove_seeded_varieties(apps, schema_editor):
    PlantVariety = apps.get_model('geo_tracker', 'PlantVariety')
    for plant_type, varieties in (('tree', TREE_VARIETIES), ('plant', PLANT_VARIETIES)):
        PlantVariety.objects.filter(
            plant_type=plant_type,
            name__in=[name for name, _ in varieties],
        ).delete()


